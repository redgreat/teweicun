DROP VIEW IF EXISTS v_fund_payment_source;
CREATE OR REPLACE VIEW v_fund_payment_source AS
WITH payment_verified AS (
    SELECT
        fpi.source_doc_type,
        fpi.source_order_id,
        SUM(COALESCE(fpi.current_verify_amount, 0)) AS verified_amount
    FROM fund_payment_item fpi
    JOIN fund_payment fp ON fp.id = fpi.statement_id
    WHERE fp.deleted_at IS NULL
      AND fp.status = 'completed'
    GROUP BY fpi.source_doc_type, fpi.source_order_id
),
purchase_sources AS (
    SELECT
        'purchase_order'::varchar(50) AS source_doc_type,
        po.id AS source_order_id,
        po.order_no AS source_order_no,
        '采购订单'::varchar(30) AS business_type,
        po.order_date,
        po.supplier_id,
        po.supplier_code,
        COALESCE(s.supplier_name, '') AS supplier_name,
        COALESCE(po.total_amount, 0)::numeric(18,2) AS order_amount,
        COALESCE(pv.verified_amount, 0)::numeric(18,2) AS verified_amount
    FROM purchase_order po
    LEFT JOIN supplier s ON s.supplier_code = po.supplier_code AND s.deleted_at IS NULL
    LEFT JOIN payment_verified pv ON pv.source_doc_type = 'purchase_order' AND pv.source_order_id = po.id
    WHERE po.deleted_at IS NULL
      AND po.order_status NOT IN ('draft', 'cancelled')

    UNION ALL

    SELECT
        'purchase_return'::varchar(50) AS source_doc_type,
        ro.id AS source_order_id,
        ro.return_no AS source_order_no,
        '采购退货抵充'::varchar(30) AS business_type,
        ro.return_date AS order_date,
        s.id AS supplier_id,
        COALESCE(ro.supplier_code, '') AS supplier_code,
        COALESCE(s.supplier_name, '') AS supplier_name,
        (-COALESCE((
            SELECT SUM(roi.quantity * COALESCE(inv.unit_cost, 0))
            FROM return_order_item roi
            LEFT JOIN inventory inv ON inv.id = roi.inventory_id
            WHERE roi.return_id = ro.id
        ), 0))::numeric(18,2) AS order_amount,
        COALESCE(pv.verified_amount, 0)::numeric(18,2) AS verified_amount
    FROM return_order ro
    LEFT JOIN supplier s ON s.supplier_code = ro.supplier_code AND s.deleted_at IS NULL
    LEFT JOIN payment_verified pv ON pv.source_doc_type = 'purchase_return' AND pv.source_order_id = ro.id
    WHERE ro.deleted_at IS NULL
      AND ro.return_type = 'purchase_return'
      AND ro.return_status NOT IN ('draft', 'closed', 'cancelled')
)
SELECT
    source_doc_type, source_order_id, source_order_no, business_type, order_date,
    supplier_id, supplier_code, supplier_name,
    order_amount,
    verified_amount,
    (order_amount - verified_amount)::numeric(18,2) AS unverified_amount,
    CASE
        WHEN ABS(order_amount - verified_amount) < 0.005 THEN 'completed'
        WHEN ABS(verified_amount) > 0 THEN 'partial'
        ELSE 'pending'
    END AS verify_status
FROM purchase_sources;

DROP VIEW IF EXISTS v_fund_collection_source;
CREATE OR REPLACE VIEW v_fund_collection_source AS
WITH collection_verified AS (
    SELECT
        fci.source_doc_type,
        fci.source_order_id,
        SUM(COALESCE(fci.current_verify_amount, 0)) AS verified_amount
    FROM fund_collection_item fci
    JOIN fund_collection fc ON fc.id = fci.statement_id
    WHERE fc.deleted_at IS NULL
      AND fc.status = 'completed'
    GROUP BY fci.source_doc_type, fci.source_order_id
),
sales_sources AS (
    SELECT
        'sales_order'::varchar(50) AS source_doc_type,
        so.id AS source_order_id,
        so.order_no AS source_order_no,
        '销售订单'::varchar(30) AS business_type,
        so.order_date,
        so.customer_id,
        so.customer_code,
        COALESCE(so.customer_name, c.customer_name, '') AS customer_name,
        COALESCE(so.total_amount, 0)::numeric(18,2) AS order_amount,
        COALESCE(cv.verified_amount, 0)::numeric(18,2) AS verified_amount
    FROM sales_order so
    LEFT JOIN customer c ON c.customer_code = so.customer_code AND c.deleted_at IS NULL
    LEFT JOIN collection_verified cv ON cv.source_doc_type = 'sales_order' AND cv.source_order_id = so.id
    WHERE so.deleted_at IS NULL
      AND so.order_status NOT IN ('draft', 'cancelled')

    UNION ALL

    SELECT
        'sales_return'::varchar(50) AS source_doc_type,
        ro.id AS source_order_id,
        ro.return_no AS source_order_no,
        '销售退货抵充'::varchar(30) AS business_type,
        ro.return_date AS order_date,
        c.id AS customer_id,
        COALESCE(ro.customer_code, '') AS customer_code,
        COALESCE(ro.customer_name, c.customer_name, '') AS customer_name,
        (-COALESCE((
            SELECT SUM(roi.quantity * COALESCE(soi.unit_price, inv.unit_cost, 0))
            FROM return_order_item roi
            LEFT JOIN sales_order ref_so ON ref_so.id = ro.ref_doc_id AND ro.ref_doc_type = 'sales_order'
            LEFT JOIN sales_order_item soi ON soi.order_id = ref_so.id AND soi.material_id = roi.material_id
            LEFT JOIN inventory inv ON inv.id = roi.inventory_id
            WHERE roi.return_id = ro.id
        ), 0))::numeric(18,2) AS order_amount,
        COALESCE(cv.verified_amount, 0)::numeric(18,2) AS verified_amount
    FROM return_order ro
    LEFT JOIN customer c ON c.customer_code = ro.customer_code AND c.deleted_at IS NULL
    LEFT JOIN collection_verified cv ON cv.source_doc_type = 'sales_return' AND cv.source_order_id = ro.id
    WHERE ro.deleted_at IS NULL
      AND ro.return_type = 'sales_return'
      AND ro.return_status NOT IN ('draft', 'closed', 'cancelled')
)
SELECT
    source_doc_type, source_order_id, source_order_no, business_type, order_date,
    customer_id, customer_code, customer_name,
    order_amount,
    verified_amount,
    (order_amount - verified_amount)::numeric(18,2) AS unverified_amount,
    CASE
        WHEN ABS(order_amount - verified_amount) < 0.005 THEN 'completed'
        WHEN ABS(verified_amount) > 0 THEN 'partial'
        ELSE 'pending'
    END AS verify_status
FROM sales_sources;

CREATE INDEX IF NOT EXISTS idx_fund_payment_item_source
    ON fund_payment_item (source_doc_type, source_order_id);

CREATE INDEX IF NOT EXISTS idx_fund_collection_item_source
    ON fund_collection_item (source_doc_type, source_order_id);

