BEGIN;

CREATE TABLE IF NOT EXISTS fund_payment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_no varchar(30) NOT NULL UNIQUE,
    supplier_id bigint NOT NULL,
    payer_id bigint NOT NULL,
    statement_date date NOT NULL,
    payment_amount numeric(18,2) DEFAULT 0,
    discount_amount numeric(18,2) DEFAULT 0,
    advance_amount numeric(18,2) DEFAULT 0,
    settlement_method varchar(50),
    settlement_account varchar(50),
    settlement_no varchar(50),
    remark text,
    status varchar(20) NOT NULL DEFAULT 'draft',
    created_by bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint,
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE TABLE IF NOT EXISTS fund_payment_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id bigint NOT NULL,
    source_order_id bigint NOT NULL,
    source_order_no varchar(30) NOT NULL,
    business_type varchar(30) NOT NULL,
    order_date date NOT NULL,
    order_amount numeric(18,2) DEFAULT 0,
    verified_amount numeric(18,2) DEFAULT 0,
    unverified_amount numeric(18,2) DEFAULT 0,
    current_verify_amount numeric(18,2) DEFAULT 0,
    custom_tax_amount numeric(18,2) DEFAULT 0,
    remark text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fund_collection (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_no varchar(30) NOT NULL UNIQUE,
    customer_id bigint NOT NULL,
    payee_id bigint NOT NULL,
    statement_date date NOT NULL,
    collection_amount numeric(18,2) DEFAULT 0,
    discount_amount numeric(18,2) DEFAULT 0,
    advance_amount numeric(18,2) DEFAULT 0,
    settlement_method varchar(50),
    settlement_account varchar(50),
    settlement_no varchar(50),
    remark text,
    status varchar(20) NOT NULL DEFAULT 'draft',
    created_by bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint,
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE TABLE IF NOT EXISTS fund_collection_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id bigint NOT NULL,
    source_order_id bigint NOT NULL,
    source_order_no varchar(30) NOT NULL,
    business_type varchar(30) NOT NULL,
    order_date date NOT NULL,
    order_amount numeric(18,2) DEFAULT 0,
    verified_amount numeric(18,2) DEFAULT 0,
    unverified_amount numeric(18,2) DEFAULT 0,
    current_verify_amount numeric(18,2) DEFAULT 0,
    custom_tax_amount numeric(18,2) DEFAULT 0,
    remark text,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE purchase_order ADD COLUMN IF NOT EXISTS verified_amount numeric(18,2) DEFAULT 0;
ALTER TABLE sales_order ADD COLUMN IF NOT EXISTS verified_amount numeric(18,2) DEFAULT 0;

ALTER TABLE fund_payment
    ADD COLUMN IF NOT EXISTS bill_type varchar(20) NOT NULL DEFAULT 'cash',
    ADD COLUMN IF NOT EXISTS invoice_amount numeric(18,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS actual_amount numeric(18,2) NOT NULL DEFAULT 0;

ALTER TABLE fund_collection
    ADD COLUMN IF NOT EXISTS bill_type varchar(20) NOT NULL DEFAULT 'cash',
    ADD COLUMN IF NOT EXISTS invoice_amount numeric(18,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS actual_amount numeric(18,2) NOT NULL DEFAULT 0;

ALTER TABLE fund_payment_item
    ADD COLUMN IF NOT EXISTS source_doc_type varchar(50) NOT NULL DEFAULT 'purchase_order';

ALTER TABLE fund_collection_item
    ADD COLUMN IF NOT EXISTS source_doc_type varchar(50) NOT NULL DEFAULT 'sales_order';

UPDATE fund_payment
SET actual_amount = payment_amount
WHERE COALESCE(actual_amount, 0) = 0
  AND COALESCE(payment_amount, 0) <> 0;

UPDATE fund_collection
SET actual_amount = collection_amount
WHERE COALESCE(actual_amount, 0) = 0
  AND COALESCE(collection_amount, 0) <> 0;

COMMENT ON COLUMN fund_payment.bill_type IS '票款类型：cash-款项，invoice-票据，offset-抵充';
COMMENT ON COLUMN fund_payment.invoice_amount IS '票据金额';
COMMENT ON COLUMN fund_payment.actual_amount IS '实际付款金额';
COMMENT ON COLUMN fund_payment_item.source_doc_type IS '来源单据类型：purchase_order/purchase_return';
COMMENT ON COLUMN fund_collection.bill_type IS '票款类型：cash-款项，invoice-票据，offset-抵充';
COMMENT ON COLUMN fund_collection.invoice_amount IS '票据金额';
COMMENT ON COLUMN fund_collection.actual_amount IS '实际收款金额';
COMMENT ON COLUMN fund_collection_item.source_doc_type IS '来源单据类型：sales_order/sales_return';

DROP VIEW IF EXISTS v_fund_payment_list;
CREATE OR REPLACE VIEW v_fund_payment_list AS
SELECT
    p.id, p.statement_no, p.supplier_id,
    COALESCE(s.supplier_name, '') AS supplier_name,
    COALESCE(s.supplier_code, '') AS supplier_code,
    p.payer_id, COALESCE(u.real_name, u.username, '') AS payer_name,
    p.statement_date,
    COALESCE(p.bill_type, 'cash') AS bill_type,
    COALESCE(p.payment_amount, 0) AS payment_amount,
    COALESCE(p.invoice_amount, 0) AS invoice_amount,
    COALESCE(p.actual_amount, 0) AS actual_amount,
    COALESCE(p.discount_amount, 0) AS discount_amount,
    COALESCE(p.advance_amount, 0) AS advance_amount,
    COALESCE(p.settlement_method, '') AS settlement_method,
    COALESCE(p.settlement_account, '') AS settlement_account,
    COALESCE(p.settlement_no, '') AS settlement_no,
    COALESCE(p.remark, '') AS remark,
    p.status, p.created_at, p.updated_at, p.deleted_at,
    COALESCE(p.payment_amount, 0) - COALESCE(p.actual_amount, 0) AS difference_amount
FROM fund_payment p
LEFT JOIN supplier s ON p.supplier_id = s.id
LEFT JOIN sys_user u ON p.payer_id = u.id
WHERE p.deleted_at IS NULL;

